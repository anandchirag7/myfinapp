import { describe, expect, it } from "./test-framework";
import {
  economicImpact,
  economicTypeFromLegacy,
  type EconomicType,
} from "../lib/statement-domain";
import { parseHdfcNarration } from "../lib/hdfc-narration";
import { extractRowsFromAOA } from "../lib/statement-parse.server";
import { auditBalanceContinuity } from "../lib/statement-ledger";
import { resolveEconomicType } from "../lib/statement-economic-resolver";
import { statementSourceFingerprint } from "../lib/statement-source-fingerprint";
import {
  linkExactReferenceOpposites,
  linkReversalGroups,
  parseNarrationFingerprint,
  type ReferenceOppositeCandidate,
  type ReversalCandidate,
} from "../lib/statement-fingerprint";
import { detectRecurringCandidates } from "../lib/statement-recurring";
import { escapeStatementCsvCell } from "../lib/statement-export";
import { resolveFinancialIdentity } from "../lib/financial-entities";
import { economicReportProjection } from "../lib/reports-fetch";
import { applyEconomicCorrection, economicCorrectionKey } from "../lib/statement-corrections";

const header = [
  "Date",
  "Narration",
  "Chq./Ref.No.",
  "Value Dt",
  "Withdrawal Amt.",
  "Deposit Amt.",
  "Closing Balance",
];

export function registerStatementFinancialEventTests() {
  describe("HDFC financial event import foundation", () => {
    it("keeps economic meaning independent from statement direction", () => {
      const zeroImpact: EconomicType[] = [
        "INTERNAL_TRANSFER",
        "CREDIT_CARD_PAYMENT",
        "INVESTMENT",
        "INVESTMENT_REDEMPTION",
        "BROKERAGE_SETTLEMENT",
        "LOAN_PAYMENT",
        "REVERSAL",
        "CASH_WITHDRAWAL",
        "CASH_DEPOSIT",
        "VERIFICATION_TRANSACTION",
        "UNKNOWN",
      ];
      for (const economicType of zeroImpact) {
        const impact = economicImpact(economicType, "debit", 500);
        expect(impact.spending).toBe(0);
        expect(impact.income).toBe(0);
      }
      expect(economicImpact("EXPENSE", "debit", 500).spending).toBe(500);
      expect(economicImpact("INSURANCE_PAYMENT", "debit", 500).spending).toBe(500);
      expect(economicImpact("REFUND", "credit", 500).spending).toBe(-500);
      expect(economicImpact("INCOME", "credit", 500).income).toBe(500);
      expect(economicImpact("INTEREST_INCOME", "credit", 500).income).toBe(500);
      expect(economicTypeFromLegacy("income", "credit")).toBe("INCOME");
    });

    it("preserves every HDFC evidence field and source row", () => {
      const rows = extractRowsFromAOA([
        ["Account statement generated by HDFC Bank"],
        header,
        [
          "18/04/26",
          "NEFT CR-YESB0000001-ZERODHA BROKING LTD-DSCNB A/C",
          "YESF361086763960",
          "18/04/26",
          null,
          836.92,
          32655.86,
        ],
      ]);
      expect(rows.length).toBe(1);
      expect(rows[0]).toEqual({
        date: "2026-04-18",
        valueDate: "2026-04-18",
        description: "NEFT CR-YESB0000001-ZERODHA BROKING LTD-DSCNB A/C",
        reference: "YESF361086763960",
        debit: null,
        credit: 836.92,
        closingBalance: 32655.86,
        amount: 836.92,
        direction: "credit",
        type: "income",
        sourceRowNumber: 3,
        rawCells: [
          "18/04/26",
          "NEFT CR-YESB0000001-ZERODHA BROKING LTD-DSCNB A/C",
          "YESF361086763960",
          "18/04/26",
          null,
          836.92,
          32655.86,
        ],
      });
    });

    it("normalizes sparse worksheet cells to JSON-safe null values", () => {
      const rows = extractRowsFromAOA([
        header,
        [
          "19/04/26",
          "UPI-SPARSE MERCHANT-SPARSE@YBL-123456789012",
          undefined,
          undefined,
          250,
          undefined,
          32405.86,
          undefined,
        ],
      ]);

      expect(rows.length).toBe(1);
      expect(rows[0].rawCells).toEqual([
        "19/04/26",
        "UPI-SPARSE MERCHANT-SPARSE@YBL-123456789012",
        null,
        null,
        250,
        null,
        32405.86,
        null,
      ]);
      expect(JSON.stringify(rows[0].rawCells)).toBe(
        '["19/04/26","UPI-SPARSE MERCHANT-SPARSE@YBL-123456789012",null,null,250,null,32405.86,null]',
      );
    });

    it("reports the exact row where closing-balance continuity breaks", () => {
      const rows = extractRowsFromAOA([
        header,
        ["01/04/26", "UPI-ALPHA-A@YBL", "REF1", "01/04/26", 100, null, 900],
        ["01/04/26", "UPI-BETA-B@YBL", "REF2", "01/04/26", null, 50, 960],
      ]);
      const audit = auditBalanceContinuity(rows);
      expect(audit.checkedTransitions).toBe(1);
      expect(audit.issues.length).toBe(1);
      expect(audit.issues[0].sourceRowNumber).toBe(3);
      expect(audit.issues[0].delta).toBe(10);
    });

    it("parses HDFC UPI into stable structured fields", () => {
      const parsed = parseHdfcNarration(
        "UPI-INDMONEY-INDMONEY1X.RZP@ICICI-ICIC0DC0099-109614311897-PAY VIA RAZORPAY",
      );
      expect(parsed.rail).toBe("upi");
      expect(parsed.counterparty).toBe("INDMONEY");
      expect(parsed.vpa).toBe("INDMONEY1X.RZP@ICICI");
      expect(parsed.bankCode).toBe("ICIC0DC0099");
      expect(parsed.railReference).toBe("109614311897");
      expect(parsed.processor).toBe("RAZORPAY");
    });

    it("parses HDFC return, mandate, IMPS and NEFT evidence", () => {
      const returned = parseHdfcNarration("UPIRET-610101561331-ZERODHA-RETURN");
      expect(returned.rail).toBe("upi");
      expect(returned.subtype).toBe("return");
      expect(returned.originalReference).toBe("610101561331");

      const mandate = parseHdfcNarration("ACH D- RACPC BANSAWADI BENG-NODNHTSYM260");
      expect(mandate.rail).toBe("ach");
      expect(mandate.subtype).toBe("debit");
      expect(mandate.counterparty).toBe("RACPC BANSAWADI BENG");
      expect(mandate.mandateReference).toBe("NODNHTSYM260");

      const imps = parseHdfcNarration(
        "IMPS-611853909102-CHIRAG SBI BANK ACCOUNT-SBIN-XXXXXXX3753-IMPS TRANSACTION",
      );
      expect(imps.railReference).toBe("611853909102");
      expect(imps.bankCode).toBe("SBIN");
      expect(imps.accountHint).toBe("XXXXXXX3753");

      const neft = parseHdfcNarration(
        "NEFT CR-CITI0000004-INTEL TECHNOLOGY I PVT LTD-CHIRAG ANAND-CITIN26658495708",
      );
      expect(neft.subtype).toBe("credit");
      expect(neft.bankCode).toBe("CITI0000004");
      expect(neft.railReference).toBe("CITIN26658495708");
    });

    it("resolves protected financial movements before merchant categories", () => {
      const cases: Array<[string, "debit" | "credit", number, EconomicType]> = [
        ["UPI-CRED CLUB-CRED.CLUB@AXISB-PAYMENT ON CRED", "debit", 43626.78, "CREDIT_CARD_PAYMENT"],
        ["NEFT DR-NPS TIER 1-NET BANKING SI -NPS CONTRIBUTION", "debit", 5000, "INVESTMENT"],
        ["UPI-INDIAN CLEARING CORP-ZERODHA.ICCL7.BRK@VALIDYES-NOTIFICATION", "debit", 1000, "INVESTMENT"],
        ["NEFT CR-YESB0000001-ZERODHA BROKING LTD-DSCNB A/C", "credit", 836.92, "BROKERAGE_SETTLEMENT"],
        ["ACH D- RACPC BANSAWADI BENG-NODNHTSYM260", "debit", 32569, "LOAN_PAYMENT"],
        ["ACH D-TATA AIA LIFE-POLICY XXXX01", "debit", 12000, "INSURANCE_PAYMENT"],
        ["NEFT CR-EMPLOYER-SALARY", "credit", 100000, "INCOME"],
        ["INTEREST PAID", "credit", 420, "INTEREST_INCOME"],
        ["ACH C-CORPORATE ACTION DIVIDEND-ISIN IN000000", "credit", 267.75, "INVESTMENT_INCOME"],
        ["UPIRET-610101561331-ZERODHA-RETURN", "credit", 1000, "REVERSAL"],
        ["ACH DEBIT RETURN CHARGES 060426-EPR2711148934656", "debit", 590, "FEE_OR_CHARGE"],
      ];
      for (const [description, direction, amount, expected] of cases) {
        expect(resolveEconomicType({ description, direction, amount }).economicType).toBe(expected);
      }
    });

    it("recognizes a payment received on an owned card statement", () => {
      expect(
        resolveEconomicType({
          description: "PAYMENT RECEIVED - THANK YOU",
          direction: "credit",
          amount: 43_626.78,
          accountCategory: "credit_card",
        }).economicType,
      ).toBe("CREDIT_CARD_PAYMENT");
      expect(
        resolveEconomicType({
          description: "PAYMENT RECEIVED - CUSTOMER",
          direction: "credit",
          amount: 43_626.78,
          accountCategory: "bank",
        }).economicType,
      ).toBe("UNKNOWN");
    });

    it("requires contextual evidence before treating a one-rupee row as verification", () => {
      expect(
        resolveEconomicType({
          description: "IMPS-609627057778-APIBANKING-RATN-XXXX0168-ACCOUNTVALIDATION",
          direction: "credit",
          amount: 1,
        }).economicType,
      ).toBe("VERIFICATION_TRANSACTION");
      expect(
        resolveEconomicType({ description: "UPI-TEA SHOP-TEA@YBL", direction: "debit", amount: 1 })
          .economicType,
      ).toBe("EXPENSE");
    });

    it("fingerprints repeated same-amount rows without collapsing distinct source rows", async () => {
      const row = {
        date: "2026-04-06",
        valueDate: "2026-04-06",
        description: "ACH D- TP ACH INDIANESIGN-2158229779",
        reference: "0000003366324180",
        debit: 500,
        credit: null,
        closingBalance: -439.73,
        amount: 500,
        direction: "debit" as const,
        type: "expense" as const,
        sourceRowNumber: 35,
      };
      const first = await statementSourceFingerprint(row);
      expect(first.length).toBe(64);
      expect(await statementSourceFingerprint({ ...row })).toBe(first);
      expect(await statementSourceFingerprint({ ...row, sourceRowNumber: 36 })).not.toBe(first);
      expect(await statementSourceFingerprint({ ...row, closingBalance: 60.27 })).not.toBe(first);
    });

    it("matches UPI returns by exact original reference before merchant similarity", async () => {
      const debitFingerprint = await parseNarrationFingerprint({
        raw: "UPI-MERCHANT ALPHA-ALPHA@YBL-610101561331",
        direction: "debit",
        bankFormat: "HDFC",
        scopeSalt: "household",
        normalizedPattern: "MERCHANT ALPHA",
      });
      const returnFingerprint = await parseNarrationFingerprint({
        raw: "UPIRET-610101561331-DIFFERENT DISPLAY-RETURN",
        direction: "credit",
        bankFormat: "HDFC",
        scopeSalt: "household",
        normalizedPattern: "DIFFERENT DISPLAY",
      });
      const rows: ReversalCandidate[] = [
        {
          date: "2026-04-01",
          amount: 500,
          type: "expense" as const,
          pattern: "MERCHANT ALPHA",
          fingerprint: debitFingerprint,
          reference: "0000610101561331",
        },
        {
          date: "2026-04-02",
          amount: 500,
          type: "income" as const,
          pattern: "DIFFERENT DISPLAY",
          fingerprint: returnFingerprint,
          originalReference: "610101561331",
        },
      ];
      linkReversalGroups(rows);
      expect(rows[0].reversal_group_id).toBe("reversal:reference:610101561331");
      expect(rows[1].reversal_group_id).toBe(rows[0].reversal_group_id);
    });

    it("detects RACPC monthly mandates without merging another amount", () => {
      const observations = [
        ["a", "2026-04-10", 32569, "NODNHTSYM260"],
        ["b", "2026-05-09", 32569, "NODNHTSYM260"],
        ["c", "2026-06-11", 32569, "NODNHTSYM260"],
        ["d", "2026-04-10", 12500, "OTHER-MANDATE"],
        ["e", "2026-05-10", 12500, "OTHER-MANDATE"],
      ].map(([key, date, amount, mandateReference]) => ({
        key: String(key),
        date: String(date),
        amount: Number(amount),
        direction: "debit" as const,
        providerKey: "RACPC BANSAWADI BENG",
        mandateReference: String(mandateReference),
      }));
      const candidates = detectRecurringCandidates(observations);
      expect(candidates.length).toBe(2);
      const loan = candidates.find((candidate) => candidate.expectedAmount === 32569)!;
      expect(loan.cadence).toBe("monthly");
      expect(loan.expectedDay).toBe(10);
      expect(loan.windowDays).toBe(1);
      expect(loan.observationKeys).toEqual(["a", "b", "c"]);
      expect(loan.confidence).toBe(0.99);
    });

    it("pairs silent HDFC ACH debit returns by exact bank reference", () => {
      const rows: ReferenceOppositeCandidate[] = [
        {
          date: "2026-04-06",
          amount: 500,
          type: "expense" as const,
          reference: "0000003366324180",
        },
        {
          date: "2026-04-06",
          amount: 500,
          type: "income" as const,
          reference: "0000003366324180",
        },
        {
          date: "2026-04-06",
          amount: 500,
          type: "income" as const,
          reference: "DIFFERENT3366324180",
        },
      ];
      linkExactReferenceOpposites(rows);
      expect(rows[0].reversal_group_id).toBe("reversal:reference:3366324180");
      expect(rows[1].reversal_group_id).toBe(rows[0].reversal_group_id);
      expect(rows[2].reversal_group_id).toBeUndefined();
    });

    it("prevents spreadsheet formula execution in statement exports", () => {
      expect(escapeStatementCsvCell("=HYPERLINK(\"https://evil.invalid\")")).toBe(
        `"'=HYPERLINK(""https://evil.invalid"")"`,
      );
      expect(escapeStatementCsvCell("  +cmd|' /C calc'!A0")).toBe("'  +cmd|' /C calc'!A0");
      expect(escapeStatementCsvCell("Normal merchant")).toBe("Normal merchant");
    });

    it("keeps financial families and payment processors separate", () => {
      const zerodha = resolveFinancialIdentity(
        "UPI-INDIAN CLEARING CORP-ZERODHA.ICCL7.BRK@VALIDYES-NOTIFICATION",
      );
      expect(zerodha.canonicalName).toBe("INDIAN CLEARING CORPORATION");
      expect(zerodha.familyName).toBe("ZERODHA");

      const indmoney = resolveFinancialIdentity(
        "UPI-FINZOOMERS SERVICES-FINZOOMERS.CF@ICICI-PAY VIA RAZORPAY",
        { processor: "RAZORPAY" },
      );
      expect(indmoney.canonicalName).toBe("FINZOOMERS SERVICES");
      expect(indmoney.familyName).toBe("INDMONEY");
      expect(indmoney.processorName).toBe("RAZORPAY");
    });

    it("projects report rows using economic rather than cash direction", () => {
      expect(
        economicReportProjection({ type: "expense", amount: 1000, economic_type: "INVESTMENT" })
          .type,
      ).toBe("investment");
      expect(
        economicReportProjection({ type: "income", amount: 500, economic_type: "REFUND" }),
      ).toEqual({
        type: "expense",
        amount: -500,
        economic_type: "REFUND",
        cash_type: "income",
        cash_amount: 500,
      });
      expect(
        economicReportProjection({ type: "income", amount: 800, economic_type: "BROKERAGE_SETTLEMENT" })
          .type,
      ).toBe("brokerage_settlement");
    });

    it("applies household economic corrections only to the exact pattern and direction", () => {
      const current = resolveEconomicType({
        description: "MYSTERY CREDIT",
        direction: "credit",
        amount: 1250,
      });
      const corrected = applyEconomicCorrection(current, {
        normalizedPattern: "MYSTERY CREDIT",
        direction: "credit",
        economicType: "REFUND",
      });
      expect(economicCorrectionKey(" mystery credit ", "credit")).toBe(
        economicCorrectionKey("MYSTERY CREDIT", "credit"),
      );
      expect(corrected.economicType).toBe("REFUND");
      expect(corrected.confidence).toBe(1);
      expect(corrected.source).toBe("user_confirmed_rule");
      expect(corrected.requiresReview).toBe(false);

      const protectedCred = resolveEconomicType({
        description: "UPI-CRED CLUB-CRED.CLUB@AXISB-123-PAYMENT ON CRED",
        direction: "debit",
        amount: 7600,
      });
      expect(
        applyEconomicCorrection(protectedCred, {
          normalizedPattern: "CRED CLUB",
          direction: "debit",
          economicType: "EXPENSE",
        }).economicType,
      ).toBe("CREDIT_CARD_PAYMENT");
    });
  });
}
